    /**
     * Returns the color called [name], or `null` when there is none.
     *
     * Matching ignores case and every character that is not a letter, so `Alice Blue`, `alice_blue`
     * and `aliceblue` all return [ALICE_BLUE].
     */
    public fun named(name: String): TextColor? = byName[name.filter { it.isLetter() }.lowercase()]

    private fun color(value: Int) = PropertyDelegateProvider<Any?, ReadOnlyProperty<Any?, TextColor>> { _, property ->
        val color = TextColor.color(value)
        byName[property.name.replace("_", "").lowercase()] = color
        ReadOnlyProperty { _, _ -> color }
    }
